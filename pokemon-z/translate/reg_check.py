    ('이 배는 성도지방으로 향하는 배입니다!', '합쇼'),
    ('그렇습니까?', '합쇼'),
    ('어디로 가십니까?', '합쇼'),
    ('알겠습니다. 다음에 또 이용해주세요!', '해요'),
    ('포켓몬을 건강한 상태로 되돌려드릴까요?', '해요'),
    ('참... 신기한 일이죠?', '해요'),
