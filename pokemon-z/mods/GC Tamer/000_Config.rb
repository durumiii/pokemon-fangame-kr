# GC Tamer — 걷는 동안 12초마다 오던 ~85ms 멈칫(루비 GC)을 길들이는 실험 모드.
# 평소에는 GC를 눌러 두고, 어차피 얼어 있는 전환 순간에 몰아서 돌린다.
# 값을 고치면 주입기를 다시 돌리고 게임 재시작: uv run mod/z/inject.py

module GcTamer
  # false로 바꾸면 아무것도 안 한다 (되돌리기 스위치).
  ENABLED = true

  # 전환(맵 이동·장면 바뀜)이 이만큼(초) 없으면 강제로 한 번 돈다.
  # 힙이 무한정 크는 것을 막는 안전판 — 이때는 멈칫이 눈에 보일 수 있다.
  FALLBACK_S = 90

  # 연속 트리거 합치기(초). 맵 이동과 장면 바뀜이 같이 걸려도 한 번만 돈다.
  MIN_GAP_S = 2

  # 수동 GC를 이 파일에 한 줄씩 남긴다 (프로파일러와 같은 파일이라 대조가 쉽다).
  # "" 이면 안 남긴다.
  LOG = "profiler.log"
end
