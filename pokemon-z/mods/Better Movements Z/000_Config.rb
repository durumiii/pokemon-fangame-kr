# Better Movements Z — 이동 조작감 (Pokemon Z v2.18 · Essentials v16 · 루비 1.8).
# 값을 고친 뒤에는 주입기를 다시 돌리고 게임을 재시작해야 반영된다:
#   uv run pokemon-z/inject.py "Better Movements Z"

module BetterMovementsZ
  # 속도 눈금 표: 바닐라 값 => 바꿀 값.
  # 바닐라는 걷기 3.8 · 달리기/서핑/얼음 4.8 · 자전거 5.2.
  # 눈금은 지수라 0.3을 더하면 약 23% 빨라진다 (2**0.3 = 1.23).
  #
  # ── 눈금은 아무 값이나 쓰면 화면이 흔들린다 (2026-08-04) ────────────────────
  #
  # 게임은 프레임마다 `2 ** 눈금`만큼 **실좌표**를 민다(`Game_Character#update_move`).
  # 한 칸은 실좌표 128이고 화면 픽셀은 그것을 4로 나눈 값이라
  # (`screen_x`가 `(real_x - display_x + 3) / 4`), 프레임당 화면 이동은 이렇다.
  #
  #   px/프레임 = 2 ** 눈금 / 4
  #
  # 이게 정수가 아니면 걸음 폭이 프레임마다 달라진다. 게다가 한 칸 끝에서 남은
  # 거리만큼만 미는 클램프가 있어 마지막 프레임이 반 걸음으로 잘린다. 카메라는
  # 캐릭터가 움직인 거리를 그대로 따라 스크롤하므로(`Game_Player#update`) 어긋나는
  # 대신 **화면 전체가 같이 널뛴다**. 프레임은 하나도 안 밀렸는데 움직인 거리만
  # 들쭉날쭉한 것이라 프로파일러에는 안 잡히고 눈에만 보인다.
  #
  # 고른 값은 `2 ** 눈금`이 4의 배수이면서 128을 나눠떨어뜨리는 것뿐 — 곧 **정수
  # 눈금**이다. 프레임레이트도 해상도도 안 탄다(프레임 수가 아니라 프레임당 거리가
  # 정해지는 방식이라서). 60fps 기준으로 쓸 수 있는 칸은 넷이다.
  #
  #   눈금 3 →  2px/프레임 · 16프레임/칸 · 0.267초/칸
  #   눈금 4 →  4px/프레임 ·  8프레임/칸 · 0.133초/칸
  #   눈금 5 →  8px/프레임 ·  4프레임/칸 · 0.067초/칸
  #   눈금 6 → 16px/프레임 ·  2프레임/칸 · 0.033초/칸
  #
  # 바닐라는 셋 다 소수라 원래부터 안 고르다. 한 칸을 건너는 걸음 폭:
  #   걷기   3.8 = 3.48px/프레임  [4, 3, 4, 3, 4, 3, 4, 3, 4, 0]
  #   달리기 4.8 = 6.96px/프레임  [7, 7, 7, 7, 4]
  #   자전거 5.2 = 9.19px/프레임  [9, 10, 9, 4]
  #
  # 칸 사이에 중간값이 없다 — 한 단 오르면 두 배다. 걷기와 달리기는 가까운 칸이
  # 체감을 거의 안 바꿔서 정수로 옮겼고, 자전거는 어느 쪽으로 가도 크게 달라져서
  # 소수인 채로 뒀다. 자리마다의 셈은 아래 주석에.
  SPEED = {
    # 걷기 — 4.29px/프레임(4.1)에서 4.00으로. 걸음 폭이 [4]×8로 완전히 고르다.
    # 속도는 7% 느려지지만 바닐라(3.48px)보다는 여전히 15% 빠르다.
    3.8 => 4,

    # 달리기 — 6.96px/프레임(바닐라 4.8)에서 8.00으로. 걸음 폭이 [8]×4로 고르다.
    # 15% 빨라지는데, 한때 되돌린 5.1(8.57px)보다는 느리다 (2026-08-04 사용자 판정).
    # **서핑과 얼음 미끄러짐도 같은 눈금이라 함께 빨라진다** — 게임이 셋에 같은 4.8을
    # 박기 때문에 표의 열쇠 하나로 묶여 있고, 따로 가르려면 열쇠가 아니라 상황을 봐야 한다.
    4.8 => 5,

    # 자전거 — 아직 안 고르다(11.31px/프레임, 걸음 폭 [12, 11, 9]).
    # 가까운 칸 둘 다 체감이 크게 달라진다. 눈금 5는 8.00px이라 지금보다 43% 느리고
    # 바닐라 자전거(9.19px)보다도 느려진다. 눈금 6은 16.00px이라 41% 빨라지는데
    # 한 칸을 두 프레임에 건너는 속도다. 실기 체감으로 고를 자리.
    5.2 => 5.5
  }

  # 방향키를 새로 눌렀을 때 제자리 회전에서 이동으로 넘어가는 문턱(프레임).
  # 바닐라 2. 0이면 최소 한 프레임 회전 뒤 바로 걷는다. 2보다 크게는 못 둔다.
  TURN_DELAY_FRAMES = 1
end
