# Better Movements Z — 이동 조작감 (Pokemon Z v2.18 · Essentials v16 · 루비 1.8).
# 값을 고친 뒤에는 주입기를 다시 돌리고 게임을 재시작해야 반영된다:
#   uv run mod/z/inject.py "Better Movements Z"

module BetterMovementsZ
  # 속도 눈금 표: 바닐라 값 => 바꿀 값. 게임은 프레임마다 2**눈금 픽셀씩 민다.
  # 바닐라는 걷기 3.8 · 달리기/서핑/얼음 4.8 · 자전거 5.2.
  # 0.3을 더하면 약 23% 빨라진다 (2**0.3 = 1.23).
  SPEED = {
    3.8 => 4.1,   # 걷기
    4.8 => 5.1,   # 달리기·서핑·얼음
    5.2 => 5.5    # 자전거
  }

  # 방향키를 새로 눌렀을 때 제자리 회전에서 이동으로 넘어가는 문턱(프레임).
  # 바닐라 2. 0이면 최소 한 프레임 회전 뒤 바로 걷는다. 2보다 크게는 못 둔다.
  TURN_DELAY_FRAMES = 1
end
